function grav(tc)
 return (9.8067*tc^2)/2
end

function arcy(tc,a,b,c)
 return ((((tc)-a)/b)^2+c)
end

function pullimage(lnum)
 vbank(1)
 cls(5)
 if lnum<135 and lnum>-1 then
  memcpy(0x0000+lnum*120,0x8000,(136-lnum)*120)
 end
 if lnum<0 then
  memcpy(0x0000,0x8000,136*120)
 end
 vbank(0)
end
 
function drawstars(t)
 for i=1,300 do
  if i%6>2 then
   pix(stars.x[i],stars.y[i],13+(i)%3)
  end
  if i%6==0 then 
   pix(stars.x[i],stars.y[i],14+(0.9*sin((t+i)/6))//1)
  end
  if i%6==1 then 
   pix(stars.x[i],stars.y[i],13+(1.1*cos((t+i)/6))//1)
  end
  if i%6==2 then 
   pix(stars.x[i],stars.y[i],12+abs(3.1*sin((t+i)/6))//1)
  end
 end
end
 
function launchfirework(index,tc,cutoff)
 if (tc-1.5)<cutoff then
  circ((tc-1.5)*firework[index].off+120,arcy(tc-1.5,firework[index].a,firework[index].b,firework[index].c),1,firework[index].col[4])
 end 
 if (tc-1)<cutoff then
  circ((tc-1)*firework[index].off+120,arcy(tc-1,firework[index].a,firework[index].b,firework[index].c),1,firework[index].col[3])
 end 
 if (tc-.5)<cutoff then
  circ((tc-.5)*firework[index].off+120,arcy(tc-.5,firework[index].a,firework[index].b,firework[index].c),1,firework[index].col[2])
 end 
 if tc<cutoff then
  circ(tc*firework[index].off+120,arcy(tc,firework[index].a,firework[index].b,firework[index].c),1,firework[index].col[1])
 end 
end

