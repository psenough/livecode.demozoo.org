function RLE_Unpack(sourcepic)
 local vidindex=0
 local picend=#sourcepic//2-1
 for i=0,picend do
 local colend=sourcepic[i*2+1]
  if colend == 1 then
   poke4(0x8000*2+vidindex,sourcepic[i*2+2])
   vidindex=vidindex+1 
  else
   for j=0,colend-1 do
    poke4(0x8000*2+vidindex,sourcepic[i*2+2])
    vidindex=vidindex+1 
   end
  end
 end
end

