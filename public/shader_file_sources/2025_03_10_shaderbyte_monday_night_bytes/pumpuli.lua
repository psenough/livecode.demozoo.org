frm=0
BPM=130
function TIC()
	local X,Y,x,y,xx,yy=0,0,0,0,0,0
	local f,flc,low,hi=0,0,0,0
	frm=frm+1
	t=time()/60000*BPM
	flc=fft(0,1023)
	low=ffts(0,32)
	hi=ffts(32,512)
	for i=1,1023 do
		ft[i]=ft[i]*.9+fft(i-1)
	end
	vbank(0)
	for yy=0,H,STP do 
		for xx=0,W,STP do
			x=xx+frm%STP
			y=yy+(frm//STP)%STP
			X=x/W-.5
			Y=y/H-.5
			X,Y=rot(X,Y,low*.08-hi*.08)
			X,Y=rot(X,Y,X*Y*sin(t/8+ft[abs(X*W*0.8)//1+1]))
			X=(X*(.9+(t//1-t)*.1)+.5)%1-.5
			Y=(Y*(.9+(t//1-t)*.1)+.5)%1-.5
			
			for i=0,2 do
				X=abs(X)-.08*hi
				Y=abs(Y)-.08*low
				X,Y=rot(X,Y,t*.02)
			end
			X=abs(X*W)
			Y=abs(Y*H)
			f=ft[X//1+1]*0.01%16--fft(x)/flc
			fx=fft(Y)*10
			f=f*500
			c=(Y+f)/H*16
			c=c+fx*10
			c=min(15,c)
			c=c+f+t//1
			c=c*(1-dth[(x*y)%#dth+1]*.01*f)
			pix(xx+frm%STP,yy+(frm//STP)%STP,c)
		end
	end
	vbank(1)
end

